def classify(risk):
    for cap, label in RISK_LEVELS:
        if risk <= cap:
            return label
    return "Critical"


def compute_risk(slope_factor, history_factor, rain72, intensity, moisture):
    rain_norm = min(rain72 / 150, 1)
    intensity_norm = min(intensity / 25, 1)
    moisture_norm = min(moisture / 100, 1)
    risk = (rain_norm * 0.30) + (intensity_norm * 0.30) + (slope_factor * 0.20) + (moisture_norm * 0.10) + (history_factor * 0.10)
    return min(risk, 1.0)
def get_open_meteo_data(latitude, longitude):
    data = get_weather(latitude, longitude)

    if not data:
        return None

    return {
        "temperature": data.get("temperature", 0),
        "humidity": data.get("humidity", 0),
        "current_rain": data.get("current_rain", 0),
        "rain72": data.get("rain72", 0)
    }
def get_conn():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    fresh = not os.path.exists(DB_PATH)
    conn = get_conn()
    cur = conn.cursor()
    cur.execute("""CREATE TABLE IF NOT EXISTS stations (
        id TEXT PRIMARY KEY, name TEXT, desc TEXT,
        slope_factor REAL, history_factor REAL, lat REAL, lon REAL, slope_angle REAL, elevation REAL, drainage REAL, soil_type TEXT
    )""")
    cur.execute("""CREATE TABLE IF NOT EXISTS readings (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        station_id TEXT, tick INTEGER,
        rain72 REAL, intensity REAL, moisture REAL, risk REAL,
        ts TEXT
    )""")
    cur.execute("""CREATE TABLE IF NOT EXISTS alerts (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        station_id TEXT, station_name TEXT, level TEXT, message TEXT, ts TEXT
    )""")
    cur.execute("""CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT)""")
    conn.commit()

    # Lightweight schema migration for databases created by the older prototype.
    existing_cols = {r[1] for r in cur.execute("PRAGMA table_info(stations)").fetchall()}
    migrations = {"lat":"REAL", "lon":"REAL", "slope_angle":"REAL", "elevation":"REAL", "drainage":"REAL", "soil_type":"TEXT"}
    for col, typ in migrations.items():
        if col not in existing_cols:
            cur.execute(f"ALTER TABLE stations ADD COLUMN {col} {typ}")
    cur.execute("UPDATE stations SET lat=25.86,lon=91.88,slope_angle=34,elevation=520,drainage=0.45,soil_type='Loose regolith' WHERE id='nongpoh' AND lat IS NULL")
    cur.execute("UPDATE stations SET lat=25.77,lon=91.90,slope_angle=31,elevation=610,drainage=0.38,soil_type='Weathered rock' WHERE id='umsning' AND lat IS NULL")
    cur.execute("UPDATE stations SET lat=26.04,lon=91.91,slope_angle=39,elevation=430,drainage=0.30,soil_type='Clay-rich soil' WHERE id='byrnihat' AND lat IS NULL")
    cur.execute("UPDATE stations SET lat=25.68,lon=91.90,slope_angle=35,elevation=970,drainage=0.62,soil_type='Residual soil' WHERE id='barapani' AND lat IS NULL")
    cur.execute("UPDATE stations SET lat=26.12,lon=91.87,slope_angle=19,elevation=160,drainage=0.72,soil_type='Dense alluvium' WHERE id='jorabat' AND lat IS NULL")
    conn.commit()

    cur.execute("SELECT COUNT(*) as c FROM stations")
    if cur.fetchone()["c"] == 0:
        for s in STATIONS:
            cur.execute(
                "INSERT INTO stations (id,name,desc,slope_factor,history_factor,lat,lon,slope_angle,elevation,drainage,soil_type) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                (s["id"], s["name"], s["desc"], s["slope_factor"], s["history_factor"], s["lat"], s["lon"], s["slope_angle"], s["elevation"], s["drainage"], s["soil_type"]),
            )
        conn.commit()

    cur.execute("SELECT COUNT(*) as c FROM readings")
    if cur.fetchone()["c"] == 0:
        seed_baseline(conn)

    cur.execute("SELECT COUNT(*) as c FROM meta WHERE key='tick'")
    if cur.fetchone()["c"] == 0:
        cur.execute("INSERT INTO meta (key,value) VALUES ('tick','0')")
        conn.commit()

    conn.close()
    if fresh:
        print(f"Created new database at {DB_PATH}")


def seed_baseline(conn):
    cur = conn.cursor()
    ts = datetime.datetime.now().isoformat()
    for s in STATIONS:
        risk = compute_risk(s["slope_factor"], s["history_factor"], s["rain72"], s["intensity"], s["moisture"])
        cur.execute(
            "INSERT INTO readings (station_id,tick,rain72,intensity,moisture,risk,ts) VALUES (?,?,?,?,?,?,?)",
            (s["id"], 0, s["rain72"], s["intensity"], s["moisture"], risk, ts),
        )
    conn.commit()


def get_state():
    conn = get_conn()
    cur = conn.cursor()

    cur.execute("SELECT * FROM stations")
    stations = [dict(r) for r in cur.fetchall()]

    for s in stations:
        cur.execute(
            "SELECT * FROM readings WHERE station_id=? ORDER BY tick DESC LIMIT 1",
            (s["id"],),
        )
        latest = cur.fetchone()
        s["rain72"] = latest["rain72"]
        s["intensity"] = latest["intensity"]
        s["moisture"] = latest["moisture"]
        s["risk"] = latest["risk"]
        s["level"] = classify(latest["risk"])
        s["rain24"] = min(s["rain72"] * 0.48, s["rain72"])
        s["forecast6h"] = min(180, s["intensity"] * 3.5 + s["rain72"] * 0.08)
        s["tilt_rate"] = round(max(0.05, (s["risk"] * 4.5) - 1.0), 2)
        features = {"rain24": s["rain24"], "rain72": s["rain72"], "intensity": s["intensity"], "moisture": s["moisture"], "slope_angle": s.get("slope_angle") or 30, "elevation": s.get("elevation") or 500, "drainage": s.get("drainage") or 0.5, "history": s["history_factor"], "tilt_rate": s["tilt_rate"], "forecast6h": s["forecast6h"]}
        s["ai_probability"] = predict(features)
        s["ai_level"] = classify(s["ai_probability"])
        s["ai_factors"] = feature_contributions(features)
        s["prediction_window"] = "next 6 hours"
        if s["ai_level"] == "Critical":
            s["action"] = "Issue immediate warning and inspect/restrict the exposed road section."
        elif s["ai_level"] == "High":
            s["action"] = "Increase monitoring and inspect slope movement and drainage."
        elif s["ai_level"] == "Moderate":
            s["action"] = "Continue enhanced monitoring; check drainage after heavy rain."
        else:
            s["action"] = "Normal monitoring."

        cur.execute(
            "SELECT tick, risk FROM readings WHERE station_id=? ORDER BY tick DESC LIMIT 25",
            (s["id"],),
        )
        hist = [dict(r) for r in cur.fetchall()]
        hist.reverse()
        s["history"] = hist

    cur.execute("SELECT * FROM alerts ORDER BY id DESC LIMIT 50")
    alerts = [dict(r) for r in cur.fetchall()]

    cur.execute("SELECT value FROM meta WHERE key='tick'")
    tick = int(cur.fetchone()["value"])

    conn.close()
    return {"stations": stations, "alerts": alerts, "tick": tick}


def simulate_step():
    conn = get_conn()
    cur = conn.cursor()
    ts = datetime.datetime.now().isoformat()

    cur.execute("SELECT value FROM meta WHERE key='tick'")
    tick = int(cur.fetchone()["value"]) + 1

    cur.execute("SELECT * FROM stations")
    stations = [dict(r) for r in cur.fetchall()]

    for s in stations:
        cur.execute(
            "SELECT * FROM readings WHERE station_id=? ORDER BY tick DESC LIMIT 1",
            (s["id"],),
        )
        latest = dict(cur.fetchone())
        prior_level = classify(latest["risk"])

        storm_factor = 1 + s["slope_factor"] * 0.6 + s["history_factor"] * 0.4
        new_intensity = min(latest["intensity"] + 0.9 * storm_factor, 30)
        new_rain72 = min(latest["rain72"] + new_intensity * 0.6, 220)
        new_moisture = min(latest["moisture"] + 1.4, 95)
        new_risk = compute_risk(s["slope_factor"], s["history_factor"], new_rain72, new_intensity, new_moisture)
        new_level = classify(new_risk)

        cur.execute(
            "INSERT INTO readings (station_id,tick,rain72,intensity,moisture,risk,ts) VALUES (?,?,?,?,?,?,?)",
            (s["id"], tick, new_rain72, new_intensity, new_moisture, new_risk, ts),
        )

        if new_level != prior_level and new_level in ("High", "Critical"):
            message = (
                f"risk escalated to CRITICAL ({new_risk*100:.0f}%) — recommend immediate advisory"
                if new_level == "Critical"
                else f"risk escalated to HIGH ({new_risk*100:.0f}%) — heightened monitoring advised"
            )
            cur.execute(
                "INSERT INTO alerts (station_id,station_name,level,message,ts) VALUES (?,?,?,?,?)",
                (s["id"], s["name"], new_level, message, ts),
            )
            send_alert(s["name"], new_level, message)

    cur.execute("UPDATE meta SET value=? WHERE key='tick'", (str(tick),))
    conn.commit()
    conn.close()


def ingest_reading(station_id: str, rain72: float, intensity: float, moisture: float) -> dict:
    """Record a real (non-simulated) reading pushed by a sensor/weather feed."""
    conn = get_conn()
    cur = conn.cursor()

    cur.execute("SELECT * FROM stations WHERE id=?", (station_id,))
    station = cur.fetchone()
    if not station:
        conn.close()
        raise ValueError(f"Unknown station_id '{station_id}'")
    station = dict(station)

    cur.execute("SELECT value FROM meta WHERE key='tick'")
    tick = int(cur.fetchone()["value"]) + 1

    cur.execute(
        "SELECT * FROM readings WHERE station_id=? ORDER BY tick DESC LIMIT 1",
        (station_id,),
    )
    latest = cur.fetchone()
    prior_level = classify(latest["risk"]) if latest else "Low"

    new_risk = compute_risk(station["slope_factor"], station["history_factor"], rain72, intensity, moisture)
    new_level = classify(new_risk)
    ts = datetime.datetime.now().isoformat()

    cur.execute(
        "INSERT INTO readings (station_id,tick,rain72,intensity,moisture,risk,ts) VALUES (?,?,?,?,?,?,?)",
        (station_id, tick, rain72, intensity, moisture, new_risk, ts),
    )

    alert_fired = False
    notification = None
    if new_level != prior_level and new_level in ("High", "Critical"):
        message = (
            f"risk escalated to CRITICAL ({new_risk*100:.0f}%) — recommend immediate advisory"
            if new_level == "Critical"
            else f"risk escalated to HIGH ({new_risk*100:.0f}%) — heightened monitoring advised"
        )
        cur.execute(
            "INSERT INTO alerts (station_id,station_name,level,message,ts) VALUES (?,?,?,?,?)",
            (station_id, station["name"], new_level, message, ts),
        )
        notification = send_alert(station["name"], new_level, message)
        alert_fired = True

    cur.execute("UPDATE meta SET value=? WHERE key='tick'", (str(tick),))
    conn.commit()
    conn.close()

    return {"risk": new_risk, "level": new_level, "alert_fired": alert_fired, "notification": notification}


def reset_state():
    conn = get_conn()
    cur = conn.cursor()
    cur.execute("DELETE FROM readings")
    cur.execute("DELETE FROM alerts")
    cur.execute("UPDATE meta SET value='0' WHERE key='tick'")
    conn.commit()
    seed_baseline(conn)
    conn.close()


