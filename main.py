app = FastAPI(
    title="SlopeSense — Landslide Early Warning API",
    description="Typed REST API for the SlopeSense landslide monitoring prototype.",
    version="2.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.on_event("startup")
def on_startup():
    init_db()


@app.get("/", include_in_schema=False)
def serve_index():
    return FileResponse(os.path.join(STATIC_DIR, "index.html"))


@app.get("/api/health", response_model=HealthResponse)
def health():
    return HealthResponse(ok=True, ai_model="logistic_regression_demo", database=DB_PATH)


@app.get("/api/state", response_model=StateResponse)
def api_state():
    try:
        return get_state()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to read state: {e}")

@app.get("/api/weather/{station_id}")
def api_weather(station_id: str):

    station = next(
        (s for s in STATIONS if s["id"] == station_id),
        None
    )

    if not station:
        raise HTTPException(
            status_code=404,
            detail="Station not found"
        )

    weather = get_open_meteo_data(
        station["lat"],
        station["lon"]
    )

    if weather is None:
        raise HTTPException(
            status_code=500,
            detail="Could not fetch weather data"
        )

    return {
        "station_id": station_id,
        "station_name": station["name"],
        "latitude": station["lat"],
        "longitude": station["lon"],
        "weather": weather
    }
@app.get("/api/live-risk/{station_id}")
def api_live_risk(station_id: str):

    station = next(
        (s for s in STATIONS if s["id"] == station_id),
        None
    )

    if not station:
        raise HTTPException(
            status_code=404,
            detail="Station not found"
        )

    weather = get_open_meteo_data(
        station["lat"],
        station["lon"]
    )

    if weather is None:
        raise HTTPException(
            status_code=500,
            detail="Could not fetch weather data"
        )

    # Real rainfall from Open-Meteo
    rain72 = weather["rain72"]

    # Existing station values
    intensity = station["intensity"]
    moisture = station["moisture"]

    # Calculate landslide risk
    risk = compute_risk(
       station["slope_factor"],
       station["history_factor"],
       rain72,
       intensity,
       moisture
    )

    risk_level = classify(risk)

    return {
        "station_id": station_id,
        "station_name": station["name"],
        "weather": {
            "temperature": weather["temperature"],
            "humidity": weather["humidity"],
            "current_rain": weather["current_rain"],
            "rain72": rain72
        },
        "landslide_risk": {
            "score": round(risk, 3),
            "level": risk_level
        }
    }
@app.post("/api/simulate/step", response_model=StateResponse)
def api_simulate_step():
    try:
        simulate_step()
        return get_state()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Simulation step failed: {e}")


@app.post("/api/reset", response_model=StateResponse, dependencies=[Depends(require_api_key)])
def api_reset():
    try:
        reset_state()
        return get_state()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Reset failed: {e}")


@app.post("/api/telemetry", response_model=TelemetryResult, dependencies=[Depends(require_api_key)])
def api_telemetry(data: TelemetryInput):
    """
    Ingest a real sensor / weather-feed reading for one station.
    Requires header:  X-API-Key: <SLOPESENSE_API_KEY>
    This is the integration point a real rain gauge, soil-moisture probe,
    or third-party weather API would call instead of the simulator.
    """
    try:
        result = ingest_reading(data.station_id, data.rain72, data.intensity, data.moisture)
    except ValueError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Ingestion failed: {e}")
    return TelemetryResult(station_id=data.station_id, **result)


