class TelemetryInput(BaseModel):
    """Payload a real sensor / weather-feed integration would POST."""
    station_id: str = Field(..., description="Must match an existing station id, e.g. 'nongpoh'")
    rain72: float = Field(..., ge=0, description="Cumulative rainfall over the last 72h, mm")
    intensity: float = Field(..., ge=0, description="Current rainfall intensity, mm/hr")
    moisture: float = Field(..., ge=0, le=100, description="Soil moisture, percent")


class TelemetryResult(BaseModel):
    station_id: str
    risk: float
    level: str
    alert_fired: bool
    notification: Optional[dict] = None


