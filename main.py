class HealthResponse(BaseModel):
    ok: bool
    ai_model: str
    database: str


class ReadingPoint(BaseModel):
    tick: int
    risk: float


class AIFactor(BaseModel):
    factor: str
    impact: float


class Station(BaseModel):
    id: str
    name: str
    desc: str
    slope_factor: float
    history_factor: float
    lat: float
    lon: float
    slope_angle: float
    elevation: float
    drainage: float
    soil_type: str
    rain72: float
    intensity: float
    moisture: float
    risk: float
    level: str
